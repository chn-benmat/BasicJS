/*
ตัวดำเนินการทางคณิตศาสตร์ ->

บวก (+) -> ใช้ในการบวกค่า

ลบ (-) -> ใช้ในการลบค่า

คูณ (*) -> ใช้ในการคูณค่า

หาร (/) -> ใช้ในการหารค่า

เอาเศษ (%) -> ใช้ในการหาเศษจากการหาร

ยกกำลัง (**) -> ใช้ในการยกกำลัง

ตัวดำเนินการทางเปรียบเทียบ ->

เท่ากับ (==) -> 
        ใช้ในการเปรียบเทียบว่าสอดคล้องกันหรือไม่ (หลีกเลี่ยงในการใช้ในการเปรียบเทียบค่าแบบ Strict Equality)

ไม่เท่ากับ (!=) -> 
        ใช้ในการเปรียบเทียบว่าไม่สอดคล้องกันหรือไม่ (หลีกเลี่ยงในการใช้ในการเปรียบเทียบค่าแบบ Strict Inequality)

เท่ากับ (Strict Equality) (===) -> 
        ใช้ในการเปรียบเทียบค่าและประเภทข้อมูลว่าเท่ากันหรือไม่

ไม่เท่ากับ (Strict Inequality) (!==) -> ใช้ในการเปรียบเทียบค่าและประเภทข้อมูลว่าไม่เท่ากันหรือไม่

มากกว่า (>) -> 
        ใช้ในการเปรียบเทียบว่าค่าด้านซ้ายมากกว่าค่าด้านขวาหรือไม่.

น้อยกว่า (<) -> 
        ใช้ในการเปรียบเทียบว่าค่าด้านซ้ายน้อยกว่าค่าด้านขวาหรือไม่

มากกว่าหรือเท่ากับ (>=) -> 
        ใช้ในการเปรียบเทียบว่าค่าด้านซ้ายมากกว่าหรือเท่ากับค่าด้านขวาหรือไม่

น้อยกว่าหรือเท่ากับ (<=) -> 
        ใช้ในการเปรียบเทียบว่าค่าด้านซ้ายน้อยกว่าหรือเท่ากับค่าด้านขวาหรือไม่

ตัวดำเนินการทางตรรกศาสตร์ -> 
        
ตารางทางตรรกศาสตร์
-----------------------------------
true และ true ได้ true
true และ false ได้ false
false และ false ได้ false
ttruหรือ true ได้ true
true หรือ false ได้ true
false หรือ false ได้ false
ไม่ true ได้ false
ไม่ false ได้ true
-----------------------------------
และ (&&) -> ใช้ในการตรวจสอบทั้งสองเงื่อนไขว่าเป็นจริงหรือไม่

หรือ (||) -> ใช้ในการตรวจสอบว่าอย่างน้อยหนึ่งเงื่อนไขเป็นจริง

ไม่ (!) -> ใช้ในการเปลี่ยนค่าจริงเป็นเท็จ หรือค่าเท็จเป็นจริง

ตัวดำเนินการเพิ่มค่า ลดค่า (Increment/Decrement) -> 
        
เพิ่มค่า (++) -> ใช้ในการเพิ่มค่าของตัวแปร

ลดค่า (--) -> ใช้ในการลดค่าของตัวแปร

ตัวดำเนินการ Compound Assignment -> 
        
เพิ่มค่าและกำหนดค่า (+=) -> 
        ใช้ในการเพิ่มค่าและกำหนดค่าใหม่ให้กับตัวแปร

ลดค่าและกำหนดค่า (-=) -> 
        ใช้ในการลดค่าและกำหนดค่าใหม่ให้กับตัวแปร

คูณค่าและกำหนดค่า (*=) -> 
        ใช้ในการคูณค่าและกำหนดค่าใหม่ให้กับตัวแปร

หารค่าและกำหนดค่า (/=) -> 
        ใช้ในการหารค่าและกำหนดค่าใหม่ให้กับตัวแปร

เอาเศษและกำหนดค่า (%=) -> 
        ใช้ในการหาเศษและกำหนดค่าใหม่ให้กับตัวแปร

ยกกำลังและกำหนดค่า (**=) -> 
        ใช้ในการยกกำลังและกำหนดค่าใหม่ให้กับตัวแปร
*/

