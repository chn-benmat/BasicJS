/*
HTTP -> Hypertext Transfer Protocol
        เป็นโปรโตคอลที่ใช้สื่อสารข้อมูลระหว่างเครือข่ายอินเทอร์เน็ต 
        โดยทั่วไปใช้สำหรับการรับและส่งข้อมูลระหว่างเว็บเบราว์เซอร์ของผู้ใช้และเว็บเซิร์ฟเวอร์

GET -> 
        เป็นหนึ่งในเมทอดของ HTTP ที่ใช้ในการขอข้อมูลจากเซิร์ฟเวอร์ โดยพารามิเตอร์ส่วนใหญ่จะถูกส่งผ่าน 

URL ->
        หรือแทรกในส่วนของ URL นั้นๆ (query string). การใช้ GET ไม่ควรใช้ในการส่งข้อมูลที่เป็นความลับ 
        เนื่องจากข้อมูลจะถูกแสดงใน URL และสามารถถูกบันทึกได้

POST->
        ใช้สำหรับการส่งข้อมูลที่ต้องการการปรับเปลี่ยน state บนเซิร์ฟเวอร์ 
        เช่นการส่งข้อมูลการล็อกอิน, การส่งข้อมูลฟอร์มที่มีข้อมูลความลับ

PUT -> 
        เป็นเมทอดของ HTTP ที่ใช้ในการอัปเดตหรือแก้ไขข้อมูลที่อยู่ในทรัพยากรที่ระบุใน URI (Uniform Resource Identifier). 
        ในบางกรณี, PUT จะถูกใช้เพื่อสร้างทรัพยากรใหม่ถ้าทรัพยากรนั้นยังไม่ได้มีอยู่.

PATCH ->
        เป็นเมทอดของ HTTP ที่ใช้ในการอัปเดตเฉพาะส่วนหนึ่งของข้อมูลที่อยู่ในทรัพยากรที่ระบุใน URI 
        โดยการส่งข้อมูลที่ต้องการอัปเดตมาในรูปแบบของ "เฉพาะส่วนที่ต้องการ" ไม่จำเป็นต้องส่งข้อมูลทั้งหมด.

DELETE ->
        เป็นเมทอดของ HTTP ที่ใช้ในการลบทรัพยากรที่ระบุใน URI.

การใช้งาน
GET ->
        ใช้สำหรับการดึงข้อมูล เช่นการเรียกดูหน้าเว็บ, การค้นหา, 
        หรือการแสดงข้อมูลที่ไม่ต้องการการปรับเปลี่ยน state บนเซิร์ฟเวอร์.

POST ->
        ใช้สำหรับการส่งข้อมูลที่ต้องการการปรับเปลี่ยน state บนเซิร์ฟเวอร์ เช่นการส่งข้อมูลการล็อกอิน, 
        การส่งข้อมูลฟอร์มที่มีข้อมูลความลับ.

PUT ->
        ใช้เมื่อต้องการอัปเดตข้อมูลทั้งหมดในทรัพยากร หรือสร้างทรัพยากรใหม่ถ้ายังไม่มี.

PATCH ->
        ใช้เมื่อต้องการอัปเดตเพียงบางส่วนของข้อมูลที่อยู่ในทรัพยากร.

DELETE ->
        ใช้เมื่อต้องการลบทรัพยากร.

Fetch -> 
        การใช้คำสั่งเพื่อไปขอข้อมูลหรือส่งข้อมูลไปยังที่อื่นบนอินเตอร์เน็ต
        อาจเป็นการดึงข้อมูลจากเว็บไซต์อื่นหรือบริการอื่น ๆ บนอินเตอร์เน็ต หรือก็คือการดึงข้อมูลจาก api มาใช้

 API -> Application Programming Interface
        ชุดข้อกำหนดที่กำหนดวิธีการทำงานหรือติดต่อสื่อสารระหว่างซอฟต์แวร์หรือแอปพลิเคชันที่ต่างกันไป 
        โดย API ทำหน้าที่เป็นตัวกลางที่อนุญาตให้แอปพลิเคชันต่าง ๆ สื่อสารหรือทำงานร่วมกันได้ 

 Web API -> 
        ชุดข้อกำหนดที่อนุญาตให้แอปพลิเคชันหรือซอฟต์แวร์ต่าง ๆ สื่อสารกันผ่านเครือข่ายอินเทอร์เน็ต (หรือเว็บ) 
        มักถูกใช้ในการเข้าถึงข้อมูลหรือบริการจากระบบภายนอกผ่านทางเว็บ, โดยการส่งคำขอ (request) 
        ไปยังเซิร์ฟเวอร์และรับข้อมูล (response) กลับมา
JSON ->
        รูปแบบของข้อมูลที่ใช้ในการแลกเปลี่ยนข้อมูลระหว่างแอปพลิเคชันหรือระบบที่สตริงและวัตถุของ JavaScript 
        ใช้แทนข้อมูล. JSON ถูกออกแบบให้เป็นภาษาที่เปิดเผย (open standard) 
        และเป็นที่นิยมในการส่งข้อมูลระหว่างเว็บแอปพลิเคชันและเซิร์ฟเวอร์
 
preventDefault -> ถูกใช้เพื่อไม่ให้ browser reload หรือ refresh
้headers -> นั้นมีไว้เพื่อระบุว่าข้อมูลที่จะส่งไปทาง API นั้นเป็นแบบ JSON 
JSON.stringify() -> เพื่อแปลง Object เป็น JSON string เพื่อให้สามารถส่งข้อมูลไปยัง API ที่รับข้อมูลในรูปแบบ JSON ได้
*/


const emailInput = document.querySelector("#email-input")
const passwordInput = document.querySelector("#password-input")
const registerForm = document.querySelector(".register-form")

function registterSubmit(event) {
        event.preventDefault()
        const user = {
                email: emailInput.value,
                password: passwordInput.value,
        }
        fetch("https://reqres.in/api/register", {
                        method: "POST",
                        headers: {
                                'Content-Type': 'application/json;charset=utf-8'
                        },
                        body: JSON.stringify(user)
                })
                .then((response) => {
                        return response.json();
                })
                .then((json) => {
                        alert(`สมัครสมาขิก id = ${json.id} เรียบร้อย`)
                })
                .catch((error) => {
                        console.log(error.message);
                })

}
registerForm.addEventListener("submit", registterSubmit)