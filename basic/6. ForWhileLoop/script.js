/*
while loop ->
    ใช้สำหรับทำซ้ำบล็อกของโค้ดตามเงื่อนไขที่กำหนด. โค้ดในบล็อกจะถูกทำซ้ำไปเรื่อย ๆ จนกว่าเงื่อนไขจะเป็นเท็จ

for loop ->
    ใช้สำหรับทำซ้ำบล็อกของโค้ดตามเงื่อนไข, การเพิ่มค่า, และการเริ่มต้นที่กำหนด.

do-while loop ->
    คล้ายกับ while loop, แต่มีความแตกต่างที่บล็อกของโค้ดจะถูกทำงานอย่างน้อยหนึ่งครั้ง แม้เงื่อนไขจะเป็นเท็จ.

continue statement -> 
    ใช้เพื่อข้ามการทำงานของบล็อกของ loop ในรอบปัจจุบันและทำการทดสอบเงื่อนไขในรอบถัดไป.
 */
// While Loop
let i1 = 0;
while (i1 < 5) {
    console.log(i1);
    i1++;
}

/*
ผลลัพธ์
0
1
2
3
4
*/

/*การทำงาน-> While Loop
        ตัวแปร i ถูกกำหนดค่าเริ่มต้นเป็น 0.
        เข้าสู่ while loop และทำการตรวจสอบว่า i น้อยกว่า 5 หรือไม่.
        ถ้าเงื่อนไขเป็นจริง, ทำงานในบล็อก {} ซึ่งแสดงค่าของ i และนำ i ไปบวก 1.
        ทำซ้ำขั้นตอน 2-3 จนกว่าเงื่อนไขจะเป็นเท็จ.
*/
// For Loop
for (let i = 0; i < 5; i++) {
    console.log(i);
}

/*
ผลลัพธ์
0
1
2
3
4
*/

/*การทำงาน-> For Loop
        ใน for loop, มีการกำหนดค่าเริ่มต้น (let i = 0), เงื่อนไข (i < 5), และการเพิ่มค่า (i++).
        เข้าสู่ for loop และทำการตรวจสอบเงื่อนไขว่า i น้อยกว่า 5 หรือไม่.
        ถ้าเงื่อนไขเป็นจริง, ทำงานในบล็อก {} ซึ่งแสดงค่าของ i.
        นำ i ไปบวก 1 และทำซ้ำขั้นตอน 2-3 จนกว่าเงื่อนไขจะเป็นเท็จ.
*/

// Do While Loop
let i2 = 0;
do {
    console.log(i2);
    i2++;
} while (i2 < 5);

/*
ผลลัพธ์
0
1
2
3
4
*/

/*การทำงาน-> Do While Loop
        ตัวแปร i ถูกกำหนดค่าเริ่มต้นเป็น 0.
        ทำงานในบล็อก {} ที่อยู่ภายใน do.
        เมื่อทำงานเสร็จสิ้น, ทำการตรวจสอบเงื่อนไขใน while ว่า i น้อยกว่า 5 หรือไม่.
        ถ้าเงื่อนไขเป็นจริง, ทำซ้ำขั้นตอน 2-3 จนกว่าเงื่อนไขจะเป็นเท็จ.
*/

// Continue
for (let i = 0; i < 5; i++) {
    if (i === 2) {
        continue;
    }
    console.log(i);
}

/*
ผลลัพธ์
0
1
3
4
*/

/*การทำงาน-> Continue
        ใน for loop, มีการกำหนดค่าเริ่มต้น (let i = 0), เงื่อนไข (i < 5), และการเพิ่มค่า (i++).
        เข้าสู่ for loop และทำการตรวจสอบเงื่อนไขว่า i น้อยกว่า 5 หรือไม่.
        ถ้าเงื่อนไขเป็นจริง, ทำงานในบล็อก {}.
        ในบล็อก, ทำการตรวจสอบเงื่อนไขว่า i เท่ากับ 2 หรือไม่.
        ถ้าเงื่อนไขเป็นจริง, ใช้ continue เพื่อข้ามทำงานในรอบปัจจุบันและทำซ้ำไปที่รอบถัดไป.
        นำ i ไปแสดงใน console และทำซ้ำขั้นตอน 2-5 จนกว่าเงื่อนไขใน for loop จะเป็นเท็จ.
*/


